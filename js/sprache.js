/* Eigene Ergaenzungen aus der Verwaltung (admin/woerterbuch.html): data/woerterbuch.json
   {en: {deutsch: Uebersetzung}, it: {...}, fr: {...}, es: {...}}, nur Eintraege, die vom eingebauten
   Woerterbuch abweichen oder fehlen; sie gelten vor den eingebauten. Wird auf uebersetzten Seiten
   beim Laden gelesen (kleine Datei, deshalb synchron, damit alle Skripte sie schon kennen).
   AugWoerter.basis: nur die eingebauten Texte (fuer die Verwaltung). */
(function (w, d) {
  const W = w.AugWoerter;
  const SPR = ['en', 'it', 'fr', 'es'];
  W.basis = {};
  for (const l of SPR) {
    W.basis[l] = {};
    for (const [k, v] of Object.entries(W[l])) if (typeof v === 'string') W.basis[l][k] = v;
  }
  const l = (d.documentElement.lang || '').slice(0, 2);
  if (!SPR.includes(l) || !d.currentScript) return;
  try {
    const x = new XMLHttpRequest();
    x.open('GET', new URL('../data/woerterbuch.json', d.currentScript.src).href, false);
    x.send();
    if (x.status !== 200) return;
    const eigen = JSON.parse(x.responseText)[l];
    if (eigen && typeof eigen === 'object') for (const [k, v] of Object.entries(eigen)) if (typeof v === 'string' && v) W[l][k] = v;
  } catch (e) { /* ohne die Datei gilt das eingebaute Woerterbuch */ }
})(window, document);
